// Splits prompts/original-system-prompt.md into the always-loaded base prompt
// (src/skills/core.ts) and on-demand skills (src/skills/<name>.ts).
// Skill text is moved verbatim; everything not assigned to a skill stays in core.
// Usage: node scripts/split-system-prompt.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
let base = readFileSync(join(root, "prompts/original-system-prompt.md"), "utf-8");

// Whole top-level sections, matched by heading prefix.
const SECTION_SKILLS = {
  pricing: [
    "FINANCING GEOGRAPHY",
    "HEALTH INSURANCE",
    "CARECREDIT / CHERRY",
    "PACKAGE & CLINIC FACTS",
    "DIRECT-FROM-CLINIC PRICE QUOTES",
    "WHAT MATTERS vs NICE TO HAVE",
    "PRE-ASSESSMENT CLINIC AND PRICING ANSWERS",
  ],
  "clinic-info": [
    "CLINIC WEBSITE",
    "CREATOR / PARTNERSHIP BUSINESS",
    "CLINIC STATUS TIERS",
    "TRAVEL READINESS",
  ],
  consultation: ["CONSULTATION RESCHEDULING", "PHONE CONTACT"],
  payment: ["DEPOSIT ELIGIBILITY RULE", "REVERSIBILITY", "TIME-BOUND PAUSE"],
  collection: [
    "COLLECTION PERSISTENCE",
    "INSTANT FORM AREA CONFIRMATION",
    "INFORMATION COLLECTION",
    "CONCERN REFLECTION",
    "IMAGE GUIDANCE",
    "IMAGE DELAY HANDLING",
  ],
};

// Operational Knowledge items pulled into a skill, by item number.
const OPS_ITEM_SKILLS = { 3: "assessment", 6: "payment", 8: "consultation", 9: "pricing" };

// Single GUIDELINES bullets pulled into a skill, by their opening text.
const GUIDELINE_SKILLS = { "- **No assessment turnaround promises (HARD).**": "assessment" };

const pulled = {}; // skill -> [{ pos, text }]
function pull(skill, start, end, render = (t) => t) {
  const text = base.slice(start, end);
  (pulled[skill] ??= []).push({ pos: start, text: render(text).trim() });
  base = base.slice(0, start) + base.slice(end);
}

// Sub-blocks first (they live inside sections that stay in core).
for (const [prefix, skill] of Object.entries(GUIDELINE_SKILLS)) {
  const start = base.indexOf(prefix);
  const end = base.indexOf("\n", start) + 1;
  pull(skill, start, end, (t) => `# GUIDELINES (excerpt)\n${t}`);
}

{
  const start = base.indexOf("### CONSULTATION BOOKING CONFIRMATION");
  const end = base.indexOf("## MEETING_MISSED", start);
  pull("consultation", start, end, (t) => t.replace(/^### /, "# "));
}

for (const [num, skill] of Object.entries(OPS_ITEM_SKILLS).sort((a, b) => b[0] - a[0])) {
  const opsStart = base.indexOf("# OPERATIONAL KNOWLEDGE");
  const start = base.indexOf(`\n${num}. **`, opsStart) + 1;
  const next = base.slice(start + 1).search(/\n\d+\. \*\*|\n\n\nWORKING_MEMORY_SYSTEM_INSTRUCTION/);
  const end = start + 1 + next + 1;
  pull(skill, start, end, (t) => `# OPERATIONAL KNOWLEDGE (excerpt)\n${t}`);
}

for (const [skill, headings] of Object.entries(SECTION_SKILLS)) {
  for (const heading of headings) {
    const start = base.indexOf(`\n# ${heading}`) + 1;
    if (start === 0) throw new Error(`Section not found: ${heading}`);
    const next = base.slice(start + 1).search(/\n# /);
    const end = next === -1 ? base.length : start + 1 + next + 1;
    pull(skill, start, end);
  }
}

// Positions shift as blocks are removed, so order each skill by its first
// appearance in the original document instead.
const original = readFileSync(join(root, "prompts/original-system-prompt.md"), "utf-8");
const firstLine = (t) => t.split("\n").find((l) => l.trim() && !l.endsWith("(excerpt)"));
const origPos = (t) => {
  const line = firstLine(t);
  const i = original.indexOf(`\n${line}\n`);
  // The promoted "### CONSULTATION BOOKING CONFIRMATION" heading.
  return i !== -1 ? i : original.indexOf(`\n##${line}\n`);
};

const toTs = (name, text) => {
  const escaped = text.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
  return `// Generated by scripts/split-system-prompt.mjs from prompts/original-system-prompt.md — do not edit by hand.\nexport const ${name} = \`\n${escaped}\n\`.trim();\n`;
};

const exportNames = {
  pricing: "pricingSkill",
  "clinic-info": "clinicInfoSkill",
  consultation: "consultationSkill",
  assessment: "assessmentSkill",
  payment: "paymentSkill",
  collection: "collectionSkill",
};

for (const [skill, blocks] of Object.entries(pulled)) {
  const text = blocks
    .sort((a, b) => origPos(a.text) - origPos(b.text))
    .map((b) => b.text)
    .join("\n\n");
  writeFileSync(join(root, `src/skills/${skill}.ts`), toTs(exportNames[skill], text));
}

base = base.replace(/\n{4,}/g, "\n\n\n").trim();
writeFileSync(join(root, "src/skills/core.ts"), toTs("coreSkill", base));
console.log("core:", base.length, "chars;", Object.entries(pulled).map(([s, b]) => `${s}: ${b.length} blocks`).join(", "));
